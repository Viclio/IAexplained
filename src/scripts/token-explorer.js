    function lookupToken(raw) {
      const w = normalize(raw);
      if (!w || STOP_WORDS.has(w)) return null;
      if (LEXICON[w]) {
        const e = LEXICON[w];
        return { word: w, vec: e[currentAxisSet].slice(0, 3), cat: e.cat, known: true };
      }
      if (ALIASES[w] && LEXICON[ALIASES[w]]) {
        const e = LEXICON[ALIASES[w]];
        return { word: w, vec: e[currentAxisSet].slice(0, 3), cat: e.cat, known: true };
      }
      // Mot inconnu : projeté au centre + jitter déterministe basé sur hash
      let h = 0;
      for (let i = 0; i < w.length; i++) h = ((h << 5) - h + w.charCodeAt(i)) | 0;
      const r = () => { h = (h * 9301 + 49297) & 0x7fffffff; return (h / 0x7fffffff) * 0.6 - 0.3; };
      return { word: w, vec: [r(), r(), r()], cat: "inconnu", known: false };
    }

